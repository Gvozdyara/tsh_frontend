/* ===========================================================================
 * TSH knowledge base - service worker.
 *
 * Its jobs:
 *   1. make the SPA installable as a standalone app (Chrome/Edge require a
 *      service worker with a fetch handler next to the manifest),
 *   2. keep the shell available offline (menu, article list cached by the API
 *      cache is NOT used - the API always goes to the network),
 *   3. never serve a stale application bundle: the shell files are
 *      network-first, only the immutable vendored libraries and icons are
 *      cache-first.
 * =========================================================================== */
"use strict";

var VERSION = "tsh-v1";
var SHELL_CACHE = VERSION + "-shell";
var RUNTIME_CACHE = VERSION + "-runtime";

/* Files needed to boot the SPA offline. config.js is generated by the
 * container entrypoint, so it is fetched network-first and cached at runtime. */
var SHELL = [
  "/",
  "/index.html",
  "/styles.css",
  "/app.js",
  "/api.js",
  "/manifest.webmanifest",
  "/icons/icon.svg",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/icon-maskable-512.png",
  "/icons/apple-touch-icon.png",
  "/icons/favicon-32.png",
  "/vendor/react.production.min.js",
  "/vendor/react-dom.production.min.js",
  "/vendor/htm.umd.js"
];

self.addEventListener("install", function (event) {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then(function (cache) {
        return Promise.all(
          SHELL.map(function (url) {
            var request = new Request(url, { cache: "reload" });
            return cache.add(request).catch(function () {
              /* a single missing file must not break the installation */
              return null;
            });
          })
        );
      })
      .then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener("activate", function (event) {
  event.waitUntil(
    caches
      .keys()
      .then(function (keys) {
        return Promise.all(
          keys
            .filter(function (key) { return key !== SHELL_CACHE && key !== RUNTIME_CACHE; })
            .map(function (key) { return caches.delete(key); })
        );
      })
      .then(function () { return self.clients.claim(); })
  );
});

function isCacheable(response) {
  return response && response.ok && response.type === "basic";
}

function cachePut(request, response) {
  if (!isCacheable(response)) return;
  var copy = response.clone();
  caches.open(RUNTIME_CACHE).then(function (cache) { return cache.put(request, copy); });
}

/* network first, fall back to the cache (and optionally to an offline page) */
function networkFirst(request, cacheKey, fallbackUrl) {
  return fetch(request)
    .then(function (response) {
      cachePut(request, response);
      return response;
    })
    .catch(function () {
      return caches.match(cacheKey || request).then(function (cached) {
        if (cached) return cached;
        if (fallbackUrl) return caches.match(fallbackUrl);
        return Response.error();
      });
    });
}

/* cache first, refresh in the background */
function cacheFirst(request) {
  return caches.match(request).then(function (cached) {
    if (cached) return cached;
    return fetch(request).then(function (response) {
      cachePut(request, response);
      return response;
    });
  });
}

self.addEventListener("fetch", function (event) {
  var request = event.request;
  if (request.method !== "GET") return;

  var url;
  try { url = new URL(request.url); } catch (error) { return; }
  if (url.origin !== self.location.origin) return;

  /* the API never goes through the cache: stale articles would be worse than
   * an error, and the SSE/fetch endpoints are session bound */
  if (url.pathname.indexOf("/api/") === 0 || url.pathname === "/healthz") return;

  if (request.mode === "navigate") {
    event.respondWith(networkFirst(request, request, "/index.html"));
    return;
  }

  if (url.pathname === "/sw.js" || url.pathname === "/config.js") {
    event.respondWith(networkFirst(request, request));
    return;
  }

  if (url.pathname.indexOf("/vendor/") === 0 || url.pathname.indexOf("/icons/") === 0) {
    event.respondWith(cacheFirst(request));
    return;
  }

  /* the app shell itself: always try the network so a redeploy is picked up
   * on the next reload, keep the cached copy for offline use */
  event.respondWith(networkFirst(request, request));
});
